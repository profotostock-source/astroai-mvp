    if aspect == "conjunction":
        poss, point_form = _ins.get(natal_point, ("вашим", POINT_UA.get(natal_point, natal_point)))
        aspect_phrase = f"у сполученні з {poss}"
    elif aspect == "trine":
        poss, point_form = _gen.get(natal_point, ("вашого", POINT_UA.get(natal_point, natal_point)))
